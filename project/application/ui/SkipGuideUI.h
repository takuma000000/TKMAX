		/// スキップ案内UIを更新します。
		/// </summary>
		void Update(float dt, bool canSkip);

		/// <summary>
		/// スキップ案内UIを描画します。
		/// </summary>
		void Draw(float alpha);

		/// <summary>
		/// ImGui調整項目を表示します。
		/// </summary>
		void DrawImGui();

