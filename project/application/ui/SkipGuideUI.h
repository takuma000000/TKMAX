		/// スキップゲージが最大まで溜まったかを取得します。
		/// </summary>
		bool IsSkipCompleted() const { return skipCompleted_; }

	private:
		//=============================================================
		// スプライト
		//=============================================================

		std::unique_ptr<Sprite> sprite_ = nullptr; // UIスプライト
		std::unique_ptr<Sprite> gaugeSprite_ = nullptr; // スキップゲージ用スプライト

